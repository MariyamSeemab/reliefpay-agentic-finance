// Client-side tax receipt PDFs. jsPDF is loaded on demand so it stays out of
// the main bundle.

async function loadLogo(url = '/imgs/logo.png') {
  try {
    const res = await fetch(url);
    if (!res.ok) return null;
    const blob = await res.blob();
    const dataUrl = await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });
    const size = await new Promise((resolve) => {
      const img = new Image();
      img.onload = () => resolve({ width: img.naturalWidth, height: img.naturalHeight });
      img.onerror = () => resolve(null);
      img.src = dataUrl;
    });
    return size ? { dataUrl, ...size } : null;
  } catch {
    return null;
  }
}

function formatUsd(amount) {
  return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(Number(amount) || 0);
}

export function receiptNumber(donation) {
  return `RP-TR-${String(donation.id).replace(/[^A-Za-z0-9-]/g, '')}`;
}

function drawReceipt(doc, logo, donation, donorName) {
  const left = 20;
  let y = 20;
  if (logo) {
    const height = 16;
    const width = Math.min(60, (logo.width / logo.height) * height);
    doc.addImage(logo.dataUrl, 'PNG', left, y, width, height);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    doc.text('ReliefPay', left + width + 4, y + 11);
  } else {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    doc.text('ReliefPay', left, y + 11);
  }
  y += 26;
  doc.setDrawColor(8, 126, 131);
  doc.setLineWidth(0.6);
  doc.line(left, y, 190, y);
  y += 12;

  doc.setFontSize(16);
  doc.text('Donation Tax Receipt', left, y);
  y += 12;

  const rows = [
    ['Receipt number', receiptNumber(donation)],
    ['Donor name', donorName || donation.donorName || 'Donor'],
    ['Campaign', donation.campaignTitle || '-'],
    ['Amount', `${formatUsd(donation.amount)} (USD)`],
    ['Date', donation.timestamp || '-'],
    ['Donation ID', String(donation.id)],
  ];
  if (donation.paypalOrderId) rows.push(['PayPal order ID', donation.paypalOrderId]);
  if (donation.paypalCaptureId) rows.push(['PayPal capture ID', donation.paypalCaptureId]);

  doc.setFontSize(11);
  for (const [label, value] of rows) {
    doc.setFont('helvetica', 'bold');
    doc.text(label, left, y);
    doc.setFont('helvetica', 'normal');
    doc.text(doc.splitTextToSize(String(value), 120), left + 50, y);
    y += 9;
  }

  y += 8;
  doc.setFontSize(9);
  doc.setTextColor(100);
  doc.text(
    doc.splitTextToSize(
      'This receipt was generated by ReliefPay for a PayPal sandbox demo. No real money was charged and it is not valid for tax filing.',
      170,
    ),
    left,
    y,
  );
  doc.setTextColor(0);
}

// One donation per page. A single donation gives a one-page receipt.
export async function downloadTaxReceipts(donations, { donorName, fileName } = {}) {
  const list = Array.isArray(donations) ? donations : [donations];
  if (list.length === 0) return;
  const [{ jsPDF }, logo] = await Promise.all([import('jspdf'), loadLogo()]);
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  list.forEach((donation, index) => {
    if (index > 0) doc.addPage();
    drawReceipt(doc, logo, donation, donorName);
  });
  doc.save(fileName || (list.length === 1 ? `${receiptNumber(list[0])}.pdf` : 'ReliefPay-tax-receipts.pdf'));
}
